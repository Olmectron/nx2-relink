# what is drawn for a character the font doesn't have
UNKNOWN = '...../#####/#...#/#...#/#...#/#...#/#####'


def rows(art):
    out = []
    for row in (art.split('/') if art else []):
        assert len(row) == W and set(row) <= set('#.'), f'a row that is not {W} dots: {row!r}'
        out.append(sum(1 << (W - 1 - x) for x in range(W) if row[x] == '#'))
    assert len(out) <= H
    return out + [0] * (H - len(out))


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else 'source/font_data.h'
    assert all(chr(c) in GLYPHS for c in range(32, 127)), 'a character is missing'
    lines = ['// Made by tools/make_font.py from the pictures drawn in it: change them there, not here.',
             '//', f'// {W} dots wide, {H} high; a row is a byte whose bit {W - 1} is the leftmost dot. Characters 32 to 126, then the',
             '// one drawn for a character the font doesn\'t have.', '#pragma once', '',
             f'static const int kFontW = {W};', f'static const int kFontH = {H};', 'static const int kFontFirst = 32;',
             'static const int kFontCount = 96;', '', f'static const unsigned char kFontRows[96][{H}] = {{']
    for c in range(32, 127):
        name = {'\\': 'backslash', "'": 'apostrophe'}.get(chr(c), chr(c))
        lines.append('    {' + ', '.join(f'0x{r:02x}' for r in rows(GLYPHS[chr(c)])) + f'}},  // {name}')
    lines.append('    {' + ', '.join(f'0x{r:02x}' for r in rows(UNKNOWN)) + '},  // (not in the font)')
    lines.append('};')
    with open(out, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('written:', out)


if __name__ == '__main__':
    main()
